"""Narrative-first layout for transcript, activity and conversation inputs."""
from reportlab.lib import colors
from reportlab.lib.styles import ParagraphStyle
from reportlab.platypus import Paragraph, Spacer, Table, TableStyle, KeepTogether

from .fonts import fonts, script_text


def contextual_story(report, width):
    regular, bold = fonts()
    body = ParagraphStyle('ContextBody', fontName=regular, fontSize=10, leading=14, spaceAfter=7, shaping=1)
    heading = ParagraphStyle('ContextHeading', parent=body, fontName=bold, fontSize=12, leading=16, spaceBefore=10, spaceAfter=6, keepWithNext=True)
    title = ParagraphStyle('ContextTitle', parent=heading, fontSize=20, leading=24, spaceBefore=0)
    small = ParagraphStyle('ContextSmall', parent=body, fontSize=8, leading=11, textColor=colors.HexColor('#4b5563'))
    source = ParagraphStyle('ContextSource', parent=body, fontSize=9, leading=12, spaceAfter=4)
    data = report['input']; view = report['view']; narrative = report['narrative']
    p = lambda text, style=body: Paragraph(script_text(text), style)
    story = [p('Incident review', title),
             p(f"{data['report_number']}  |  Reported {data['reported_at']}", small)]
    if data.get('synthetic'):
        story.append(p('FICTIONAL TEST SCENARIO', small))
    if report.get('preview_only'):
        story.append(p('LAYOUT PREVIEW — SIMULATED MODEL RESPONSES, NOT AN INFERENCE RESULT', small))
    elif report['report_mode'] == 'raw_review':
        story.append(p('MODEL TEXT FOR MANUAL REVIEW · FALLBACK DISABLED', small))
    story.append(p('Recorded handling priority: ' + view['priority'], heading))

    def section(label, text):
        story.extend([KeepTogether([p(label, heading), p(text)])])

    section('What was recorded', narrative['description']['text'])
    section('Interpretation', narrative['interpretation']['text'])
    section('What needs clarification', narrative['clarification']['text'])
    if report['validation_issues']:
        section('Review flags', '\n'.join(report['validation_issues']))
    story.extend([Spacer(1, 8), p('Source record', heading),
                  p(f"Observation window: {data['observation_window']['start']} to {data['observation_window']['end']}", small)])
    rows = [[p(row['signal'], small), p(row['observation'].replace('seconds.Current', 'seconds. Current'), source)] for row in view['sensor_rows']]
    table = Table(rows, colWidths=[width*.28, width*.72], hAlign='LEFT')
    table.setStyle(TableStyle([('VALIGN', (0,0), (-1,-1), 'TOP'),
                               ('LINEBELOW', (0,0), (-1,-1), .4, colors.HexColor('#d5dbe3')),
                               ('TOPPADDING', (0,0), (-1,-1), 5), ('BOTTOMPADDING', (0,0), (-1,-1), 5)]))
    story.append(table)
    for label, text in [('Transcription', view['transcript']), ('Chat context', view['chat_context'])]:
        story.append(p(label, heading))
        # Separate paragraphs can flow across pages for longer source records.
        story.extend(p(line) for line in text.splitlines())
    if view.get('keywords'):
        story.extend([p('Supplied keywords (derived hints)', heading), p(', '.join(view['keywords']))])
    if data.get('events'):
        story.append(p('Recorded events', heading))
        story.extend(p(f"{event['at']}: {event['observation']}") for event in data['events'])
    if data.get('location'):
        story.extend([p('Recorded location', heading), p(view['gps']['coordinates']), p(view['gps']['fix'], small)])
    if data['assessment']['context'] != 'insufficient_context':
        story.append(p('Backend-supplied context: ' + data['assessment']['context'], small))
    for label, key in [('Recorded status', 'recorded_status'), ('Supplied follow-up', 'follow_up')]:
        if data.get(key):
            section(label, data[key])
    if data.get('limitations'):
        section('Additional source limitations', '; '.join(data['limitations']))
    # Keep provenance with the last source block rather than on an otherwise empty page.
    tail = [story.pop()]
    while story and story[-1].getKeepWithNext():
        tail.insert(0, story.pop())
    tail.append(p('Generated by ' + report.get('model_id', 'configured model') + ' | ' + report.get('prompt_version', ''), small))
    story.append(KeepTogether(tail))
    return story
